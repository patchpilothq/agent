package main

// The agent's dependency and licence inventory. DEPENDENCIES.md is generated
// from the module graph and never edited by hand; these tests fail when it no
// longer matches, or when a dependency is under a licence the agent may not
// ship. Regenerate with:
//
//	make inventory

import (
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

var updateInventory = flag.Bool("update-inventory", false, "rewrite DEPENDENCIES.md")

// The agent is GPL-3.0-or-later, so its dependencies must be compatible with
// it. Every one of them also runs as root on a customer's server.
var allowedLicences = map[string]bool{
	"MIT": true, "Apache-2.0": true, "BSD-2-Clause": true, "BSD-3-Clause": true,
	"ISC": true, "MPL-2.0": true, "GPL-3.0": true,
}

type module struct {
	Path, Version, Dir string
	Main               bool
}

type dependency struct{ path, version, licence string }

func TestInventoryMatchesTheModuleGraph(t *testing.T) {
	want := renderInventory(dependencies(t))
	if *updateInventory {
		if err := os.WriteFile("DEPENDENCIES.md", []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile("DEPENDENCIES.md")
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != want {
		t.Fatal("DEPENDENCIES.md is stale — run `make inventory`")
	}
}

func TestEveryDependencyIsUnderAnAllowedLicence(t *testing.T) {
	for _, d := range dependencies(t) {
		if !allowedLicences[d.licence] {
			t.Errorf("%s %s: licence %q is not allowed (docs/DOSSIER.md §5)", d.path, d.version, d.licence)
		}
	}
}

// The agent has no dependencies yet, so licenceOf is proven on samples.
func TestLicenceOfRecognisesTheAllowedLicences(t *testing.T) {
	samples := map[string]string{
		"Apache License\nVersion 2.0, January 2004":                                   "Apache-2.0",
		"Mozilla Public License Version 2.0":                                          "MPL-2.0",
		"GNU GENERAL PUBLIC LICENSE\nVersion 3, 29 June 2007":                         "GPL-3.0",
		"Permission is hereby granted, free of charge, to any person":                 "MIT",
		"Permission to use, copy, modify, and/or distribute this software":            "ISC",
		"Permission to use, copy, modify, and distribute this software for any":       "ISC",
		"Redistribution and use in source and binary forms ... Neither the name of X": "BSD-3-Clause",
		"Redistribution and use in source and binary forms, with or without":          "BSD-2-Clause",
		"GNU AFFERO GENERAL PUBLIC LICENSE":                                           "unknown",
	}
	for text, want := range samples {
		dir := t.TempDir()
		if err := os.WriteFile(filepath.Join(dir, "LICENSE"), []byte(text), 0o644); err != nil {
			t.Fatal(err)
		}
		if got := licenceOf(dir); got != want {
			t.Errorf("%q: got %s, want %s", text, got, want)
		}
	}
	if got := licenceOf(t.TempDir()); got != "unknown" {
		t.Errorf("no licence file: got %s, want unknown", got)
	}
}

func dependencies(t *testing.T) []dependency {
	t.Helper()
	out, err := exec.Command("go", "list", "-m", "-json", "all").Output()
	if err != nil {
		t.Fatalf("go list: %v", err)
	}
	var deps []dependency
	decoder := json.NewDecoder(strings.NewReader(string(out)))
	for {
		var m module
		if err := decoder.Decode(&m); errors.Is(err, io.EOF) {
			break
		} else if err != nil {
			t.Fatal(err)
		}
		if !m.Main {
			deps = append(deps, dependency{m.Path, m.Version, licenceOf(m.Dir)})
		}
	}
	return deps
}

func renderInventory(deps []dependency) string {
	var b strings.Builder
	b.WriteString("# Agent dependencies\n\n" +
		"Generated by `make inventory` from the Go module graph and each\n" +
		"module's licence file. Do not edit by hand.\n\n" +
		"| Module | Version | Licence |\n| --- | --- | --- |\n")
	for _, d := range deps {
		fmt.Fprintf(&b, "| %s | %s | %s |\n", d.path, d.version, d.licence)
	}
	if len(deps) == 0 {
		b.WriteString("\nThe agent has no dependencies beyond the Go standard library.\n")
	}
	return b.String()
}

// licenceOf names the licence of the module in dir by the wording of its
// licence file. Anything it does not recognise is "unknown", which the policy
// test refuses — a human then reads the file.
func licenceOf(dir string) string {
	files, _ := filepath.Glob(filepath.Join(dir, "LICEN[CS]E*"))
	copying, _ := filepath.Glob(filepath.Join(dir, "COPYING*"))
	for _, f := range append(files, copying...) {
		text, err := os.ReadFile(f)
		if err != nil {
			continue
		}
		s := string(text)
		switch {
		case strings.Contains(s, "Apache License") && strings.Contains(s, "Version 2.0"):
			return "Apache-2.0"
		case strings.Contains(s, "Mozilla Public License Version 2.0"):
			return "MPL-2.0"
		case strings.Contains(s, "GNU GENERAL PUBLIC LICENSE") && strings.Contains(s, "Version 3"):
			return "GPL-3.0"
		case strings.Contains(s, "Permission is hereby granted, free of charge"):
			return "MIT"
		// Both wordings of the ISC licence: OSI's, and OpenBSD's older one
		// without "/or".
		case strings.Contains(s, "Permission to use, copy, modify, and/or distribute"),
			strings.Contains(s, "Permission to use, copy, modify, and distribute this software for any"):
			return "ISC"
		case strings.Contains(s, "Redistribution and use in source and binary forms"):
			if strings.Contains(s, "Neither the name") {
				return "BSD-3-Clause"
			}
			return "BSD-2-Clause"
		}
	}
	return "unknown"
}
